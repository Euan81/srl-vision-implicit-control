def main():
    global _inlet, _last_pose

    # Connect to robot
    _inlet = _connect_lsl()
    sample, _ = _inlet.pull_sample(timeout=5.0)
    if sample is None:
        raise RuntimeError("No pose sample received from z1_pos within 5 s.")
    _last_pose = np.array(sample, dtype=np.float64)
    print("Connected to z1_pos stream.")

    # Open camera. Resolution MUST match calibrate_camera.py (2K) or the loaded
    # intrinsics are for the wrong image size and every board pose is wrong.
    cap = cv2.VideoCapture(CAMERA_INDEX)
    cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))  # 2K needs MJPEG over USB
    cap.set(cv2.CAP_PROP_FRAME_WIDTH,  2560)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 1440)
    if not cap.isOpened():
        raise RuntimeError(f"Cannot open camera index {CAMERA_INDEX}.")
    _aw = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    _ah = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    print(f"Camera opened at {_aw}×{_ah}")
    if (_aw, _ah) != (2560, 1440):
        print(f"[ABORT] Requested 2560×1440 but got {_aw}×{_ah}. Intrinsics won't "
              f"match — fix the camera 2K mode before calibrating.")
        cap.release()
        raise SystemExit(1)

    print(f"\nFix the ChArUco board in the scene and move the arm to diverse poses.")
    print(f"Press SPACE to capture, ENTER to calibrate (need ≥ {MIN_CAPTURES}), Esc to quit.\n")

    # ── Load previously saved captures ───────────────────────────────────
    T_base_EE_list, T_cam_board_list, obj_pts_list, img_pts_list, capture_files = \
        _load_all_captures()
    n_loaded = len(T_base_EE_list)
    if n_loaded:
        print(f"[+] Loaded {n_loaded} existing capture(s) from {CAPTURE_DIR}")
        print(f"    Press 'X' to wipe all saved captures and start fresh.\n")
    else:
        print(f"[INFO] No existing captures found in {CAPTURE_DIR}  (starting fresh)\n")

    while True:
        ret, frame = cap.read()
        if not ret:
            print("[WARN] Camera read failed — retrying…")
            continue

        T_cam_board, annotated, n_corners, reproj_err, obj_pts, img_pts = _detect_board(frame)
        board_ok = T_cam_board is not None
        _draw_hud(annotated, len(T_base_EE_list), board_ok, n_corners, reproj_err)

        cv2.imshow("Hand-Eye Calibration", annotated)
        key = cv2.waitKey(1) & 0xFF

        # ── SPACE: capture ────────────────────────────────────────────────
        if key == ord(' '):
            if not board_ok:
                print("[SKIP] Board not detected — move arm so the full board is visible.")
                continue
            # Flush stale samples then wait for arm to settle
            while _inlet.pull_sample(timeout=0.0)[0] is not None:
                pass
            time.sleep(0.6)   # let the arm finish settling
            # Verify arm is still (position must not drift > 1 mm over 0.2 s)
            s1, _ = _inlet.pull_sample(timeout=0.5)
            time.sleep(0.2)
            s2, _ = _inlet.pull_sample(timeout=0.5)
            if s1 is None or s2 is None:
                print("[SKIP] Could not read pose — is z1_pos streaming?")
                continue
            p1 = np.array(s1[3:6])
            p2 = np.array(s2[3:6])
            drift_mm = np.linalg.norm(p2 - p1) * 1000.0
            if drift_mm > 1.0:
                print(f"[SKIP] Arm still moving ({drift_mm:.1f} mm drift) — hold still longer.")
                continue
            pose  = np.array(s2, dtype=np.float64)
            T_bEE = _pose_to_T(pose)
            T_base_EE_list.append(T_bEE)
            T_cam_board_list.append(T_cam_board)
            obj_pts_list.append(obj_pts)
            img_pts_list.append(img_pts)
            saved_path = _save_capture(T_bEE, T_cam_board, obj_pts, img_pts)
            capture_files.append(saved_path)
            n = len(T_base_EE_list)
            xyz  = T_bEE[:3, 3]
            print(f"[+] Capture {n:>2}  EE=({xyz[0]:.3f}, {xyz[1]:.3f}, {xyz[2]:.3f}) m"
                  f"  corners={n_corners}"
                  f"  reproj={reproj_err:.2f}px"
                  f"  drift={drift_mm:.2f}mm"
                  f"  → {os.path.basename(saved_path)}")
            cv2.imshow("Quality", _draw_quality_panel(T_base_EE_list, T_cam_board_list))

        # ── u: undo ───────────────────────────────────────────────────────
        elif key == ord('u'):
            if T_base_EE_list:
                T_base_EE_list.pop()
                T_cam_board_list.pop()
                obj_pts_list.pop()
                img_pts_list.pop()
                if capture_files:
                    _delete_capture(capture_files.pop())
                print(f"[-] Removed last capture.  {len(T_base_EE_list)} remaining.")
            else:
                print("[INFO] Nothing to undo.")

        # ── ENTER: calibrate ──────────────────────────────────────────────
        elif key == 13:
            n = len(T_base_EE_list)
            if n < MIN_CAPTURES:
                print(f"[SKIP] Need at least {MIN_CAPTURES} captures, have {n}.")
                continue

            print(f"\nRunning hand-eye calibration on {n} pose pairs…")
            _check_rotation_diversity(T_base_EE_list)

            try:
                best_name, T_EE_cam, pos_mm, rot_deg = _run_calibration(
                    T_base_EE_list, T_cam_board_list
                )
            except RuntimeError as exc:
                print(f"[ERROR] Calibration failed: {exc}")
                continue

            # ── Outlier pruning ───────────────────────────────────────────
            print(f"\nPruning outlier pose pairs  (threshold={PRUNE_THRESHOLD_MM} mm):")
            kept, removed_pairs = _prune_pose_pairs(
                T_base_EE_list, T_cam_board_list, T_EE_cam
            )
            if removed_pairs:
                print(f"\n  Removed {len(removed_pairs)} pair(s). "
                      f"Re-running calibration on {len(kept)} pairs…")
                sub_EE = [T_base_EE_list[i] for i in kept]
                sub_cb = [T_cam_board_list[i] for i in kept]
                try:
                    best_name, T_EE_cam, pos_mm, rot_deg = _run_calibration(
                        sub_EE, sub_cb
                    )
                except RuntimeError as exc:
                    print(f"[ERROR] Re-calibration failed: {exc}")
                    continue
            else:
                print(f"  No pairs removed — all within {PRUNE_THRESHOLD_MM} mm.")

            final_EE  = [T_base_EE_list[i] for i in kept]
            final_cb  = [T_cam_board_list[i] for i in kept]
            final_obj = [obj_pts_list[i]    for i in kept]
            final_img = [img_pts_list[i]    for i in kept]

            # ── LM reprojection-error refinement (optional) ───────────────
            if not USE_LM_REFINEMENT:
                print(f"\nLM refinement disabled — saving raw {best_name} (AX=XB) result.")
            else:
                print(f"\nRefining with Levenberg-Marquardt reprojection optimisation…")
                try:
                    T_EE_cam_lm, reproj_rms = _refine_with_reprojection(
                        T_EE_cam, final_EE, final_cb, final_obj, final_img
                    )
                    pos_mm_lm  = _position_residual_mm(T_EE_cam_lm, final_EE, final_cb)
                    rot_deg_lm = _rotation_residual_deg(T_EE_cam_lm, final_EE, final_cb)
                    print(f"  Reprojection RMS  : {reproj_rms:.3f} px")
                    print(f"  Position residual : {pos_mm_lm:.2f} mm  (AX=XB was {pos_mm:.2f} mm)")
                    print(f"  Rotation residual : {rot_deg_lm:.3f} deg  (AX=XB was {rot_deg:.3f} deg)")
                    # Accept only if BOTH position and rotation do not worsen.
                    if pos_mm_lm <= pos_mm * 1.05 and rot_deg_lm <= rot_deg * 1.05:
                        T_EE_cam = T_EE_cam_lm
                        pos_mm   = pos_mm_lm
                        rot_deg  = rot_deg_lm
                    else:
                        print("  [WARN] LM worsened pos or rot — keeping AX=XB result.")
                except Exception as exc:
                    print(f"  [WARN] LM refinement failed ({exc}) — keeping AX=XB result.")

            np.savez(OUTPUT_FILE, T_EE_cam=T_EE_cam)
            print(f"\nSaved {OUTPUT_FILE}  (method: {best_name})")
            print(f"  Pairs used        : {len(kept)} / {n}")
            print(f"  Position residual : {pos_mm:.2f} mm")
            print(f"  Rotation residual : {rot_deg:.3f} deg")
            print(f"\nT_EE_cam =\n{T_EE_cam}\n")
            cv2.imshow("Quality", _draw_quality_panel(final_EE, final_cb, T_EE_cam))
            print("Press any key in the Quality window to exit.")
            cv2.waitKey(0)
            break

        # ── x: wipe all captures and start fresh ─────────────────────────
        elif key == ord('x'):
            print(f"\nWipe ALL {len(T_base_EE_list)} capture(s) from {CAPTURE_DIR}? "
                  f"Type 'yes' in terminal and press Enter to confirm, or anything else to cancel.")
            confirm = input("> ").strip().lower()
            if confirm == "yes":
                for f in capture_files:
                    _delete_capture(f)
                T_base_EE_list.clear()
                T_cam_board_list.clear()
                obj_pts_list.clear()
                img_pts_list.clear()
                capture_files.clear()
                n_loaded = 0
                print("[X] All captures deleted.  Starting fresh.")
            else:
                print("[CANCEL] Wipe cancelled.")

        # ── Esc: quit ─────────────────────────────────────────────────────
        elif key == 27:
            print("Quit — no file saved.")
            break

    cap.release()
    cv2.destroyAllWindows()


if __name__ == "__main__":
    main()
