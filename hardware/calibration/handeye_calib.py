def _put(img, text, pt, color=(0, 220, 80), scale=0.50, thickness=1):
    cv2.putText(img, text, pt, cv2.FONT_HERSHEY_SIMPLEX, scale, (0,0,0), thickness+2, cv2.LINE_AA)
    cv2.putText(img, text, pt, cv2.FONT_HERSHEY_SIMPLEX, scale, color,   thickness,   cv2.LINE_AA)

def _draw_hud(frame, n_captures, board_ok, n_corners, reproj_err=None):
    h, w = frame.shape[:2]

    # Border: green = board good, yellow = board seen but pose bad, red = not detected
    border_col = (0, 200, 50) if board_ok else (0, 50, 220)
    cv2.rectangle(frame, (0, 0), (w - 1, h - 1), border_col, 4)

    # Status line
    if board_ok:
        status = f"Board OK  ({n_corners} corners)"
        col = (0, 200, 50)
    elif n_corners >= MIN_CORNERS and reproj_err is not None:
        status = f"Pose bad ({n_corners} corners, reproj={reproj_err:.1f}px) — face board more directly"
        col = (0, 150, 255)
    elif n_corners > 0:
        status = f"Too few corners: {n_corners} / {MIN_CORNERS} min — show more of the board"
        col = (0, 120, 255)
    else:
        status = "Board NOT DETECTED"
        col = (0, 80, 255)
    _put(frame, status, (10, 30), color=col)

    # Reprojection error when valid
    if board_ok and reproj_err is not None:
        err_col = (0, 200, 50) if reproj_err < 0.8 else (40, 180, 255)
        _put(frame, f"Reproj: {reproj_err:.2f} px", (10, 58), color=err_col)
        _put(frame, f"Captures: {n_captures} / {MIN_CAPTURES} min", (10, 84))
    else:
        _put(frame, f"Captures: {n_captures} / {MIN_CAPTURES} min", (10, 58))

    # Key hints
    hints = [
        "SPACE  capture  (green border + axes visible = ready)",
        f"ENTER  calibrate {'(ready)' if n_captures >= MIN_CAPTURES else f'(need {MIN_CAPTURES - n_captures} more)'}",
        "u      undo last    x  wipe all",
        "Esc    quit",
    ]
    for i, h_txt in enumerate(hints):
        _put(frame, h_txt, (10, h - 20 - (len(hints) - 1 - i) * 22),
             color=(200, 200, 200), scale=0.42)

