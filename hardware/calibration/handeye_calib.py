# Quality panel
# ---------------------------------------------------------------------------
def _draw_quality_panel(T_base_EE_list: list, T_cam_board_list: list,
                        T_EE_cam=None) -> np.ndarray:
    """
    Returns a 540×460 BGR image showing board-position consistency.
    Runs a fast TSAI preview if T_EE_cam is not yet available.
    Tight cluster = good calibration.  Target pos RMS < 3 mm.
    """
    W, H = 540, 460
    panel = np.full((H, W, 3), 28, dtype=np.uint8)

    N = len(T_base_EE_list)

    def pp(img, txt, pt, col=(210, 210, 210), sc=0.48, th=1):
        cv2.putText(img, txt, pt, cv2.FONT_HERSHEY_SIMPLEX, sc, (0,0,0), th+2, cv2.LINE_AA)
        cv2.putText(img, txt, pt, cv2.FONT_HERSHEY_SIMPLEX, sc, col,     th,   cv2.LINE_AA)

    pp(panel, "Board position consistency (top-down X-Y)", (10, 24),
       col=(230, 230, 230), sc=0.52)

    if N < 4:
        pp(panel, f"Capture >= 4 poses to see preview  ({N} so far)",
           (10, 60), col=(130, 130, 130))
        return panel

    # Quick TSAI solve for preview if final result not passed in
    T_use = T_EE_cam
    if T_use is None:
        try:
            R_g2b = [T[:3,:3] for T in T_base_EE_list]
            t_g2b = [T[:3,3].reshape(3,1) for T in T_base_EE_list]
            R_t2c = [T[:3,:3] for T in T_cam_board_list]
            t_t2c = [T[:3,3].reshape(3,1) for T in T_cam_board_list]
            Rc, tc = cv2.calibrateHandEye(R_g2b, t_g2b, R_t2c, t_t2c,
                                          method=cv2.CALIB_HAND_EYE_TSAI)
            T_use = np.eye(4, dtype=np.float64)
            T_use[:3,:3] = Rc;  T_use[:3,3] = tc.flatten()
        except Exception:
            pp(panel, "Preview unavailable — add more varied poses", (10, 60),
               col=(80, 80, 220))
            return panel

    # Board positions in base frame
    pts = []
    for T_bEE, T_cb in zip(T_base_EE_list, T_cam_board_list):
        p = (T_bEE @ T_use @ T_cb)[:3, 3]
        pts.append(p)
    pts = np.array(pts)                   # (N, 3)
    mean_p = pts.mean(axis=0)
    rms_mm = float(np.sqrt(np.mean(np.sum((pts - mean_p)**2, axis=1)))) * 1000.0

    # RMS colour
    if rms_mm < 3.0:
        rc = (60, 220, 60)
        grade = "GOOD"
    elif rms_mm < 8.0:
        rc = (40, 200, 230)
        grade = "OK"
    elif rms_mm < 20.0:
        rc = (40, 160, 255)
        grade = "POOR"
    else:
        rc = (60, 60, 230)
        grade = "BAD"

    label = "FINAL" if T_EE_cam is not None else "PREVIEW (TSAI)"
    pp(panel, f"Pos RMS: {rms_mm:.1f} mm  [{grade}]  {label}",
       (10, H - 14), col=rc, sc=0.52)
    pp(panel, "Target: < 3 mm", (W - 160, H - 14), col=(120, 120, 120), sc=0.40)

    # ── Scatter plot ─────────────────────────────────────────────────────
    MX, MY = 44, 44          # margin
    PW = W - 2 * MX
    PH = H - MY - 60         # leave room for title + footer

    xs = pts[:, 0] - mean_p[0]
    ys = pts[:, 1] - mean_p[1]

    # Scale so the largest deviation fills ~70 % of the plot
    max_dev = max(np.abs(xs).max(), np.abs(ys).max(), 0.005)
    scale = (min(PW, PH) * 0.35) / max_dev   # px per metre

    cx = MX + PW // 2
    cy = MY + 40 + PH // 2

    # Grid / axes
    cv2.rectangle(panel, (MX, MY + 40), (MX + PW, MY + 40 + PH), (55, 55, 55), 1)
    cv2.line(panel, (cx, MY + 40), (cx, MY + 40 + PH), (55, 55, 55), 1)
    cv2.line(panel, (MX, cy), (MX + PW, cy), (55, 55, 55), 1)

    # RMS circle
    rms_px = max(1, int(rms_mm / 1000.0 * scale))
    cv2.circle(panel, (cx, cy), rms_px, rc, 1, cv2.LINE_AA)

    # 3-mm target circle (if scale allows)
    target_px = int(0.003 * scale)
    if target_px > 2:
        cv2.circle(panel, (cx, cy), target_px, (60, 160, 60), 1, cv2.LINE_AA)
        pp(panel, "3mm", (cx + target_px + 2, cy - 4), col=(60, 160, 60), sc=0.35)

    # Data points: blue (first) → red (last)
    for i, (x, y) in enumerate(zip(xs, ys)):
        px = int(cx + x * scale)
        py = int(cy - y * scale)           # screen Y flipped
        t  = i / max(N - 1, 1)
        col = (int(255*(1-t)), 80, int(255*t))
        cv2.circle(panel, (px, py), 5, col, -1, cv2.LINE_AA)
        cv2.circle(panel, (px, py), 5, (200, 200, 200), 1, cv2.LINE_AA)

    # Mean cross
    cv2.drawMarker(panel, (cx, cy), (255, 255, 255),
                   cv2.MARKER_CROSS, 16, 2, cv2.LINE_AA)

    # Axis labels
    pp(panel, "X →", (MX + PW - 26, cy + 14), col=(140, 140, 140), sc=0.36)
    pp(panel, "↑Y",  (cx + 4, MY + 44),        col=(140, 140, 140), sc=0.36)
    pp(panel, f"±{max_dev*1000:.0f} mm",
       (MX + 2, MY + 44), col=(90, 90, 90), sc=0.36)

    # Capture index legend
    pp(panel, "● first", (MX, MY + 24), col=(255, 80, 0),  sc=0.38)
    pp(panel, "● last",  (MX + 70, MY + 24), col=(0, 80, 255), sc=0.38)

    return panel


