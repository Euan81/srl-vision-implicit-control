def _connect_lsl() -> pylsl.StreamInlet:
    print("Waiting for z1_pos LSL stream (up to 10 s)…")
    streams = pylsl.resolve_byprop("name", "z1_pos", minimum=1, timeout=10.0)
    if not streams:
        raise RuntimeError(
            "LSL stream 'z1_pos' not found after 10 s. "
            "Start the Z1 state publisher before running calibration."
        )
    inlet = pylsl.StreamInlet(streams[0])
    inlet.pull_sample(timeout=pylsl.FOREVER)   # blocking seed pull
    return inlet

_inlet:     pylsl.StreamInlet
_last_pose: np.ndarray

def _pull_pose() -> np.ndarray:
    global _last_pose
    sample, _ = _inlet.pull_sample(timeout=0.0)   # non-blocking
    if sample is not None:
        _last_pose = np.array(sample, dtype=np.float64)
    return _last_pose

def _pose_to_T(pose: np.ndarray) -> np.ndarray:
    """[roll, pitch, yaw, x, y, z] → 4×4 homogeneous matrix (ZYX Euler)."""
    roll, pitch, yaw = pose[0], pose[1], pose[2]
    x, y, z          = pose[3], pose[4], pose[5]
    cr, sr = np.cos(roll),  np.sin(roll)
    cp, sp = np.cos(pitch), np.sin(pitch)
    cy, sy = np.cos(yaw),   np.sin(yaw)
    Rx = np.array([[1, 0,  0 ], [0,  cr, -sr], [0, sr, cr]], np.float64)
    Ry = np.array([[cp, 0, sp], [0,   1,   0 ], [-sp, 0, cp]], np.float64)
    Rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]], np.float64)
    T = np.eye(4, dtype=np.float64)
    T[:3, :3] = Rz @ Ry @ Rx
    T[:3,  3] = [x, y, z]
    return T

# ---------------------------------------------------------------------------
# ChArUco pose detection  →  T_cam_board  (4×4)
# ---------------------------------------------------------------------------
def _detect_board(frame: np.ndarray):
    """
    Returns (T_cam_board, annotated_frame, n_corners, reproj_err_px, obj_pts, img_pts).
    T_cam_board is None if detection failed, not enough corners, or
    reprojection error exceeds MAX_BOARD_REPROJ_PX.
    obj_pts / img_pts are the matched 3-D / 2-D corner pairs (needed for LM refinement).
    """
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    ch_corners, ch_ids, _, _ = _cdet.detectBoard(gray)

    out = frame.copy()
    nc = 0 if ch_corners is None else len(ch_corners)

    if ch_corners is None or nc < MIN_CORNERS:
        return None, out, nc, None, None, None

    cv2.aruco.drawDetectedCornersCharuco(out, ch_corners, ch_ids, (0, 200, 255))

    obj_pts, img_pts = board.matchImagePoints(ch_corners, ch_ids)
    ok, rvec, tvec = cv2.solvePnP(
        obj_pts, img_pts, K, dist, flags=cv2.SOLVEPNP_ITERATIVE
    )
    if not ok:
        return None, out, nc, None, None, None

    proj_pts, _ = cv2.projectPoints(obj_pts, rvec, tvec, K, dist)
    reproj_err = float(np.mean(np.linalg.norm(
        img_pts.reshape(-1, 2) - proj_pts.reshape(-1, 2), axis=1
    )))

    if reproj_err > MAX_BOARD_REPROJ_PX:
        _put(out, f"Pose BAD: reproj={reproj_err:.1f}px (max {MAX_BOARD_REPROJ_PX}px) — tilt less",
             (10, 95), color=(0, 60, 255), scale=0.45)
        return None, out, nc, reproj_err, None, None

    cv2.drawFrameAxes(out, K, dist, rvec, tvec, SQUARE_M * 2)

    R, _ = cv2.Rodrigues(rvec)
    T = np.eye(4, dtype=np.float64)
    T[:3, :3] = R
    T[:3,  3] = tvec.flatten()
    return T, out, nc, reproj_err, obj_pts, img_pts

# ---------------------------------------------------------------------------
# Rotation diversity diagnostic
# ---------------------------------------------------------------------------
def _check_rotation_diversity(T_base_EE_list: list) -> float:
    """
    Print the spread of EE orientations across captured poses.
    Good hand-eye calibration needs mean pairwise angle > ~20°.
    Returns mean pairwise geodesic angle in degrees.
    """
    Rs = [T[:3, :3] for T in T_base_EE_list]
    n  = len(Rs)
    angles = []
    for i in range(n):
        for j in range(i + 1, n):
            diff    = Rs[i].T @ Rs[j]
            cos_val = np.clip((np.trace(diff) - 1.0) / 2.0, -1.0, 1.0)
            angles.append(np.degrees(np.arccos(cos_val)))
    mean_a = float(np.mean(angles))
    max_a  = float(np.max(angles))
    print(f"  EE rotation diversity:  mean={mean_a:.1f}°  max={max_a:.1f}°")
    if mean_a < 15.0:
        print("  [WARN] Very low rotation diversity — the wrist was barely rotated.")
        print("         Re-do: at each arm position, TILT the wrist in different directions.")
    elif mean_a < 25.0:
        print("  [INFO] Moderate rotation diversity — more wrist variation would help.")
    else:
        print("  [OK]   Rotation diversity looks sufficient.")
    return mean_a


# ---------------------------------------------------------------------------
# Outlier pruning for pose pairs
# ---------------------------------------------------------------------------
def _prune_pose_pairs(T_base_EE_list: list, T_cam_board_list: list,
                      T_EE_cam_init: np.ndarray):
    """
    Iteratively drop the pose pair with the highest per-pair board-position
    error until all remaining pairs are within PRUNE_THRESHOLD_MM, or
    MIN_PAIRS_AFTER_PRUNING pairs remain.
    Uses T_EE_cam_init (from the initial full calibration) for evaluation.
    Returns (kept_indices, removed_list_of_(global_idx, error_mm)).
    """
    indices = list(range(len(T_base_EE_list)))
    removed = []

    while True:
        sub_EE = [T_base_EE_list[i] for i in indices]
        sub_cb = [T_cam_board_list[i] for i in indices]

        positions = np.array(
            [(T_bEE @ T_EE_cam_init @ T_cb)[:3, 3]
             for T_bEE, T_cb in zip(sub_EE, sub_cb)]
        )
        mean_p = positions.mean(axis=0)
        errors = np.linalg.norm(positions - mean_p, axis=1) * 1000.0   # mm

        worst_local = int(np.argmax(errors))
        worst_err   = errors[worst_local]

        if worst_err <= PRUNE_THRESHOLD_MM:
            break
        if len(indices) <= MIN_PAIRS_AFTER_PRUNING:
            print(f"  [WARN] Stopped pruning at {len(indices)} pairs "
                  f"(floor={MIN_PAIRS_AFTER_PRUNING}). "
                  f"Worst remaining: {worst_err:.1f} mm.")
            break

        worst_global = indices[worst_local]
        removed.append((worst_global, worst_err))
        indices.pop(worst_local)
        print(f"  Pruned pair {worst_global + 1:>2}  "
              f"(error={worst_err:.1f} mm)  —  {len(indices)} remain")

    return indices, removed


# ---------------------------------------------------------------------------
# LM reprojection-error refinement
# ---------------------------------------------------------------------------
def _inv_T(T: np.ndarray) -> np.ndarray:
    """Efficient inversion of a 4×4 rigid-body transform."""
    R = T[:3, :3]
    t = T[:3,  3]
    Ti = np.eye(4, dtype=np.float64)
    Ti[:3, :3] = R.T
    Ti[:3,  3] = -R.T @ t
    return Ti


def _refine_with_reprojection(T_EE_cam_init: np.ndarray,
                               T_base_EE_list: list,
                               T_cam_board_list: list,
                               obj_pts_list: list,
                               img_pts_list: list) -> tuple:
    """
    Refine T_EE_cam using Levenberg-Marquardt reprojection-error minimisation.

    Jointly optimises T_EE_cam (6 DOF) and T_base_board (6 DOF) so that
    every captured board pose, projected through the current arm FK and
    the candidate T_EE_cam, minimises the sum of squared pixel errors.

    This is statistically optimal (maximum-likelihood under Gaussian noise)
    and avoids the error-propagation issue of AX=XB solvers that decouple
    rotation from translation.

    Returns (T_EE_cam_refined, reprojection_rms_px).
    """
    # ── Initial T_base_board estimate: mean position, orientation from pair 0 ──
    positions_init = np.array(
        [(T_bEE @ T_EE_cam_init @ T_cb)[:3, 3]
         for T_bEE, T_cb in zip(T_base_EE_list, T_cam_board_list)]
    )
    T_brd0 = T_base_EE_list[0] @ T_EE_cam_init @ T_cam_board_list[0]
    rv_brd0, _ = cv2.Rodrigues(T_brd0[:3, :3])
    tv_brd0    = positions_init.mean(axis=0)

    rv_cam0, _ = cv2.Rodrigues(T_EE_cam_init[:3, :3])
    tv_cam0    = T_EE_cam_init[:3, 3]

    # x = [rvec_cam(3), tvec_cam(3), rvec_board(3), tvec_board(3)]
    x0 = np.concatenate([rv_cam0.flatten(), tv_cam0,
                          rv_brd0.flatten(), tv_brd0])

    def residuals(x):
        R_cam, _ = cv2.Rodrigues(x[0:3])
        R_brd, _ = cv2.Rodrigues(x[6:9])

        T_cam = np.eye(4, dtype=np.float64)
        T_cam[:3, :3] = R_cam;  T_cam[:3, 3] = x[3:6]

        T_brd = np.eye(4, dtype=np.float64)
        T_brd[:3, :3] = R_brd;  T_brd[:3, 3] = x[9:12]

        res_all = []
        for T_bEE, obj_p, img_p in zip(T_base_EE_list, obj_pts_list, img_pts_list):
            T_cam_brd = _inv_T(T_bEE @ T_cam) @ T_brd
            rv, _  = cv2.Rodrigues(T_cam_brd[:3, :3])
            tv     = T_cam_brd[:3, 3]
            proj, _ = cv2.projectPoints(obj_p, rv, tv, K, dist)
            res_all.append((img_p.reshape(-1, 2) - proj.reshape(-1, 2)).flatten())
        return np.concatenate(res_all)

    result = least_squares(residuals, x0, method='lm', max_nfev=2000)

    R_ref, _ = cv2.Rodrigues(result.x[0:3])
    T_ref = np.eye(4, dtype=np.float64)
    T_ref[:3, :3] = R_ref
    T_ref[:3,  3] = result.x[3:6]

    final_res = residuals(result.x).reshape(-1, 2)
    rms_px = float(np.sqrt(np.mean(np.sum(final_res ** 2, axis=1))))

    return T_ref, rms_px


# ---------------------------------------------------------------------------
# Hand-eye calibration  — all five OpenCV solvers
# ---------------------------------------------------------------------------
_METHODS = {
    "TSAI":      cv2.CALIB_HAND_EYE_TSAI,
    "PARK":      cv2.CALIB_HAND_EYE_PARK,
    "HORAUD":    cv2.CALIB_HAND_EYE_HORAUD,
    "ANDREFF":   cv2.CALIB_HAND_EYE_ANDREFF,
    "DANIILIDIS": cv2.CALIB_HAND_EYE_DANIILIDIS,
}

def _make_T_EE_cam(R_c2g: np.ndarray, t_c2g: np.ndarray) -> np.ndarray:
    """Assemble T_EE_cam from calibrateHandEye output."""
    T = np.eye(4, dtype=np.float64)
    T[:3, :3] = R_c2g
    T[:3,  3] = t_c2g.flatten()
    return T

def _position_residual_mm(T_EE_cam: np.ndarray,
                           T_base_EE_list: list,
                           T_cam_board_list: list) -> float:
    """
    RMS of pairwise board-position disagreements in the base frame (mm).
    Lower is better.  A good calibration gives < 3 mm.
    """
    positions = []
    for T_bEE, T_cb in zip(T_base_EE_list, T_cam_board_list):
        T_base_board = T_bEE @ T_EE_cam @ T_cb
        positions.append(T_base_board[:3, 3])
    positions = np.array(positions)          # (N, 3)
    mean_pos  = positions.mean(axis=0)
    rms_mm    = np.sqrt(np.mean(np.sum((positions - mean_pos) ** 2, axis=1))) * 1000.0
    return rms_mm

def _rotation_residual_deg(T_EE_cam: np.ndarray,
                            T_base_EE_list: list,
                            T_cam_board_list: list) -> float:
    """Mean geodesic angle (deg) of board-rotation estimates around their mean."""
    Rs = []
    for T_bEE, T_cb in zip(T_base_EE_list, T_cam_board_list):
        Rs.append((T_bEE @ T_EE_cam @ T_cb)[:3, :3])

    # Approximate mean rotation via iterative averaging (one pass is fine here)
    R_mean = Rs[0].copy()
    for R in Rs[1:]:
        rv, _ = cv2.Rodrigues(R_mean.T @ R)
        R_mean = R_mean @ cv2.Rodrigues(rv * 0.5)[0]

    angles = []
    for R in Rs:
        diff = R_mean.T @ R
        cos_val = np.clip((np.trace(diff) - 1.0) / 2.0, -1.0, 1.0)
        angles.append(np.degrees(np.arccos(cos_val)))
    return float(np.mean(angles))

def _run_calibration(T_base_EE_list: list, T_cam_board_list: list):
    """
    Run all five solvers.  Print a comparison table.
    Return (best_name, best_T_EE_cam, pos_residual_mm, rot_residual_deg).
    """
    R_g2b = [T[:3, :3] for T in T_base_EE_list]
    t_g2b = [T[:3,  3].reshape(3, 1) for T in T_base_EE_list]
    R_t2c = [T[:3, :3] for T in T_cam_board_list]
    t_t2c = [T[:3,  3].reshape(3, 1) for T in T_cam_board_list]

    print(f"\n{'─'*60}")
    print(f"  {'Method':<12}  {'Pos RMS (mm)':>14}  {'Rot mean (deg)':>15}")
    print(f"  {'─'*12}  {'─'*14}  {'─'*15}")

    results = {}
    for name, method in _METHODS.items():
        try:
            R_c2g, t_c2g = cv2.calibrateHandEye(
                R_g2b, t_g2b, R_t2c, t_t2c, method=method
            )
            T = _make_T_EE_cam(R_c2g, t_c2g)
            pos_mm  = _position_residual_mm(T, T_base_EE_list, T_cam_board_list)
            rot_deg = _rotation_residual_deg(T, T_base_EE_list, T_cam_board_list)
            results[name] = (T, pos_mm, rot_deg)
            print(f"  {name:<12}  {pos_mm:>14.2f}  {rot_deg:>15.3f}")
        except Exception as exc:
            print(f"  {name:<12}  FAILED ({exc})")

    if not results:
        raise RuntimeError("All calibration methods failed.")

    best_name = min(results, key=lambda n: results[n][1])   # lowest pos RMS
    best_T, best_pos, best_rot = results[best_name]

    print(f"\n  Best: {best_name}  →  pos {best_pos:.2f} mm  |  rot {best_rot:.3f} deg")
    if best_pos > 5.0:
        print("  [WARN] Residual > 5 mm — consider re-doing with more varied poses.")
    print()
    return best_name, best_T, best_pos, best_rot

