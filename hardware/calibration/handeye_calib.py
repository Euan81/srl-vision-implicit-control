"""
handeye_calib.py — Interactive hand-eye calibration for the Unitree Z1 eye-in-hand setup.

Produces T_EE_cam.npz — the 4×4 homogeneous transform expressing the camera
frame in the EE (flange) frame.  Drop the file next to approach.py and you're done.

Workflow
--------
1.  Fix the ChArUco board rigidly in the scene — it must not move at all.
2.  Put the robot into gravity-compensation / teach mode.
3.  Physically move the arm to a pose where the board is fully visible.
4.  Press SPACE to capture (the border turns green when the board is detected).
5.  Repeat for at least 15 poses.  Vary wrist rotation heavily — small wrist
    rotations at different arm positions give the best conditioning.
6.  Press ENTER to run all five OpenCV solvers and save the best result.

Keys
----
  SPACE   capture current pose (board must be detected — green border)
  ENTER   run calibration and save  (requires ≥ MIN_CAPTURES poses)
  u       undo / remove last capture
  Esc     quit without saving

Requirements
------------
  pip install opencv-contrib-python numpy pylsl

Board parameters (must match gen_charuco_a4.py)
------
  5 × 7 squares, 35 mm squares, 26 mm markers, DICT_4X4_50
"""

