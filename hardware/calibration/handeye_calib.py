def _capture_files() -> list:
    """Return sorted list of capture .npz paths in CAPTURE_DIR."""
    return sorted(glob.glob(os.path.join(CAPTURE_DIR, "capture_*.npz")))


def _load_all_captures() -> tuple:
    """
    Load every saved capture from CAPTURE_DIR.
    Returns (T_base_EE_list, T_cam_board_list, obj_pts_list, img_pts_list, file_list).
    Bad/corrupt files are skipped with a warning.
    """
    files = _capture_files()
    T_EE, T_CB, OBJ, IMG, FL = [], [], [], [], []
    for f in files:
        try:
            d = np.load(f, allow_pickle=False)
            T_EE.append(d["T_base_EE"])
            T_CB.append(d["T_cam_board"])
            OBJ.append(d["obj_pts"])
            IMG.append(d["img_pts"])
            FL.append(f)
        except Exception as exc:
            print(f"[WARN] Skipping corrupt capture file {f}: {exc}")
    return T_EE, T_CB, OBJ, IMG, FL


def _save_capture(T_base_EE: np.ndarray, T_cam_board: np.ndarray,
                  obj_pts: np.ndarray, img_pts: np.ndarray) -> str:
    """
    Save one capture to CAPTURE_DIR/capture_NNNN.npz.
    The index is one higher than the current maximum so undo gaps are safe.
    Returns the saved filepath.
    """
    os.makedirs(CAPTURE_DIR, exist_ok=True)
    existing = _capture_files()
    if existing:
        last_idx = int(os.path.basename(existing[-1])
                       .replace("capture_", "").replace(".npz", ""))
        idx = last_idx + 1
    else:
        idx = 0
    path = os.path.join(CAPTURE_DIR, f"capture_{idx:04d}.npz")
    np.savez(path, T_base_EE=T_base_EE, T_cam_board=T_cam_board,
             obj_pts=obj_pts, img_pts=img_pts)
    return path


def _delete_capture(filepath: str):
    """Delete a saved capture file."""
    try:
        os.remove(filepath)
    except OSError as exc:
        print(f"[WARN] Could not delete {filepath}: {exc}")

